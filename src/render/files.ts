export function renderWebsocketClientConf(
  s: PbxSettings,
  rev: number,
  wsSecret: string,
): RenderedFile {
  // Asterisk does not fall back to the system trust store, so verification
  // without a CA bundle fails as a bare "Unable to connect" with nothing
  // pointing at the cause. There is no safe default path to emit — it is
  // distro-specific, and a wrong one fails identically — so say so in the file
  // instead, and only when the combination is actually broken.
  const missingCa =
    s.ws.tls_enabled &&
    s.ws.verify_server_cert &&
    !s.ws.ca_list_file &&
    !s.ws.ca_list_path;
  const caHint = missingCa
    ? ";; NOTE: verification is on but no CA bundle is set, and Asterisk does\n" +
      ";; not use the system trust store. Set ws.ca_list_file for this site —\n" +
      ";; /etc/ssl/certs/ca-certificates.crt on Debian, /etc/pki/tls/cert.pem\n" +
      ";; on RHEL — or add it to websocket_client_local.conf as [aem_ws](+).\n" +
      ";; Without it the connection fails with only \"Unable to connect\".\n"
    : "";

  // For persistent connections Asterisk retries forever; reconnect_attempts
  // only controls how often the failure is logged. That is exactly the
  // behaviour a cloud control plane wants — the PBX self-heals indefinitely.
  const body =
    BANNER("websocket_client.conf", rev) +
    "\n" +
    caHint +
    ini("aem_ws", {
      type: "websocket_client",
      uri: s.ws.uri,
      protocols: "ari",
      username: s.ws.username,
      password: wsSecret,
      connection_type: "persistent",
      connection_timeout: s.ws.connection_timeout,
      reconnect_interval: s.ws.reconnect_interval,
      reconnect_attempts: s.ws.reconnect_attempts,
      tls_enabled: s.ws.tls_enabled,
      ...(s.ws.ca_list_file ? { ca_list_file: s.ws.ca_list_file } : {}),
      ...(s.ws.ca_list_path ? { ca_list_path: s.ws.ca_list_path } : {}),
      verify_server_cert: s.ws.verify_server_cert,
      verify_server_hostname: s.ws.verify_server_hostname,
      enable_pingpongs: s.ws.enable_pingpongs,
      pingpong_interval: s.ws.pingpong_interval,
      pingpong_probes: s.ws.pingpong_probes,
      ...(s.ws.proxy_host ? { proxy_host: s.ws.proxy_host } : {}),
    }) +
    localInclude("websocket_client.conf");

  return { path: "websocket_client.conf", content: body };
}

export function renderAriConf(
  s: PbxSettings,
  rev: number,
  ariSecret: string,
): RenderedFile {
  // channelvars is how the call log works at all: entries containing "(" are
  // invoked as dialplan functions, so CDR() values ride along on every channel
  // event. There is no CDR event type in ARI.
  const body =
    BANNER("ari.conf", rev) +
    "\n" +
    ini("general", {
      enabled: true,
      pretty: false,
      websocket_write_timeout: 100,
      channelvars: s.ari.channelvars.join(","),
    }) +
    "\n" +
    ini(s.ari.user, {
      type: "user",
      read_only: false,
      password_format: "plain",
      password: ariSecret,
    }) +
    "\n" +
    ini("aem", {
      type: "outbound_websocket",
      websocket_client_id: "aem_ws",
      apps: s.ari.app,
      subscribe_all: true,
      local_ari_user: s.ari.user,
    }) +
    localInclude("ari.conf");

  return { path: "ari.conf", content: body };
}

export function renderCdrConf(rev: number): RenderedFile {
  // endbeforehexten defaults to "no", and cdr_object_finalize() is the only
  // place disposition and end are set. Without this an answered call reports
  // disposition NO ANSWER and end as epoch, because the channelvars are read
  // synchronously during snapshot creation, before the async CDR engine has
  // consumed that same snapshot.
  const body =
    BANNER("cdr.conf", rev) +
    "\n" +
    ini("general", {
      enable: true,
      endbeforehexten: true,
    }) +
    localInclude("cdr.conf");
  return { path: "cdr.conf", content: body };
}

export function renderSorceryConf(rev: number, sccpEnabled: boolean): RenderedFile {
  // Mapping order is lookup order, so astdb (writable, ARI-managed) is
  // consulted before the flat file (read-only, hand-maintained trunks). Both
  // backends stay visible to res_pjsip at once, which is what lets extensions
  // and trunks coexist under different ownership.
  let body =
    BANNER("sorcery.conf", rev) +
    `
[res_pjsip]
endpoint = astdb,dynamic_endpoint
endpoint = config,pjsip.conf,criteria=type=endpoint
auth = astdb,dynamic_auth
auth = config,pjsip.conf,criteria=type=auth
aor = astdb,dynamic_aor
aor = config,pjsip.conf,criteria=type=aor
`;

  if (sccpEnabled) {
    // chan_sccp2 applies this mapping programmatically via
    // ast_sorcery_apply_default, so this section is technically redundant —
    // stated explicitly so the backing store is visible to an operator reading
    // the config rather than implied by the module's source.
    body += `
[chan_sccp2]
device = astdb,chan_sccp2
line = astdb,chan_sccp2
`;
  }

  return { path: "sorcery.conf", content: body + localInclude("sorcery.conf") };
}

