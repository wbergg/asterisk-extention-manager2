export interface DialplanExtension {
  number: string;
  tech: "pjsip" | "sccp";
  /** The sorcery object id to dial: "aem-1001" for PJSIP, "1001" for SCCP. */
  dialId: string;
  directory_only: number;
  ring_timeout: number;
  no_answer_target: string;
}

export interface DialplanRingGroup {
  number: string;
  name: string;
  ring_time: number;
  no_answer_target: string;
  members: { tech: "pjsip" | "sccp"; dialId: string }[];
}

export interface DialplanQueue {
  number: string;
  name: string;
}

export interface DialplanIvr {
  number: string;
  name: string;
  greeting: string;
  timeout: number;
  invalid_target: string;
  timeout_target: string;
  entries: { digit: string; target: string }[];
}

export interface DialplanTimeCondition {
  number: string;
  name: string;
  time_spec: string;
  match_target: string;
  nomatch_target: string;
}

function dialString(tech: "pjsip" | "sccp", dialId: string): string {
  return tech === "pjsip" ? `PJSIP/${dialId}` : `SCCP/${dialId}`;
}

/** Device state key. Note SCCP keys on the *line number*, not the device id. */
function hintString(tech: "pjsip" | "sccp", dialId: string): string {
  return tech === "pjsip" ? `PJSIP/${dialId}` : `SCCP/${dialId}`;
}

export function renderExtensionsConf(
  rev: number,
  s: PbxSettings,
  data: {
    extensions: DialplanExtension[];
    ringGroups: DialplanRingGroup[];
    queues: DialplanQueue[];
    ivrs: DialplanIvr[];
    timeConditions: DialplanTimeCondition[];
  },
): RenderedFile {
  const ctx = s.dialplan.context;
  let body = BANNER("extensions.conf", rev);

  // The DO reads this back via GET asterisk/variable?variable=AEM_FILE_REV.
  // It is the only way to tell whether the operator actually applied the
  // bundle, since ARI cannot see the filesystem.
  body += `
[globals]
AEM_FILE_REV = ${rev}

[${ctx}]
`;

  for (const inc of s.dialplan.includes) {
    body += `include => ${inc}\n`;
  }

  body += "\n;; --- Extensions ---\n";
  for (const ext of data.extensions) {
    if (ext.directory_only) continue;
    body += `exten => ${ext.number},1,Dial(${dialString(ext.tech, ext.dialId)},${ext.ring_timeout})\n`;
    body += ` same => n,${ext.no_answer_target}\n`;
  }

  if (data.ringGroups.length > 0) {
    body += "\n;; --- Ring groups ---\n";
    for (const rg of data.ringGroups) {
      const targets = rg.members
        .map((m) => dialString(m.tech, m.dialId))
        .join("&");
      body += `; ${rg.name}\n`;
      body += targets
        ? `exten => ${rg.number},1,Dial(${targets},${rg.ring_time})\n`
        : `exten => ${rg.number},1,NoOp(ring group ${rg.name} has no members)\n`;
      body += ` same => n,${rg.no_answer_target}\n`;
    }
  }

  if (data.queues.length > 0) {
    body += "\n;; --- Queues ---\n";
    for (const q of data.queues) {
      body += `exten => ${q.number},1,Answer()\n`;
      body += ` same => n,Queue(${q.name})\n`;
      body += ` same => n,Hangup()\n`;
    }
  }

  if (data.timeConditions.length > 0) {
    body += "\n;; --- Time conditions ---\n";
    for (const tc of data.timeConditions) {
      body += `; ${tc.name}\n`;
      body += `exten => ${tc.number},1,GotoIfTime(${tc.time_spec}?${ctx},${tc.number},3)\n`;
      body += ` same => n,${tc.nomatch_target}\n`;
      body += ` same => n,${tc.match_target}\n`;
    }
  }

  for (const ivr of data.ivrs) {
    const ivrCtx = `${ctx}-ivr-${ivr.number}`;
    body += `\n;; --- IVR: ${ivr.name} ---\n`;
    body += `exten => ${ivr.number},1,Goto(${ivrCtx},s,1)\n`;
    body += `\n[${ivrCtx}]\n`;
    body += `exten => s,1,Answer()\n`;
    body += ` same => n,Background(${ivr.greeting})\n`;
    body += ` same => n,WaitExten(${ivr.timeout})\n`;
    for (const e of ivr.entries) {
      body += `exten => ${e.digit},1,${e.target}\n`;
    }
    body += `exten => i,1,${ivr.invalid_target}\n`;
    body += `exten => t,1,${ivr.timeout_target}\n`;
    body += `\n[${ctx}]\n`;
  }

  // Hints last so BLF and device state resolve for every extension above.
  body += "\n;; --- Hints (BLF / device state) ---\n";
  for (const ext of data.extensions) {
    if (ext.directory_only) continue;
    body += `exten => ${ext.number},hint,${hintString(ext.tech, ext.dialId)}\n`;
  }

  return {
    path: "extensions.conf",
    content: body + localInclude("extensions.conf"),
  };
}

export interface MohClass {
  name: string;
  mode: string;
  directory: string;
  sort_mode: string;
}

export function renderMusicOnHoldConf(
  rev: number,
  classes: MohClass[],
): RenderedFile {
  let body = BANNER("musiconhold.conf", rev);
  body +=
    "\n;; Note: the audio files these classes point at are NOT delivered by the\n" +
    ";; control plane. Each PBX must already have them on disk.\n";
  for (const c of classes) {
    body +=
      "\n" +
      ini(c.name, {
        mode: c.mode,
        directory: c.directory,
        sort: c.sort_mode,
      });
  }
  return {
    path: "musiconhold.conf",
    content: body + localInclude("musiconhold.conf"),
  };
}

export interface QueueDef {
  name: string;
  strategy: string;
  timeout: number;
  musicclass: string;
  attrs: Record<string, string>;
  members: { tech: "pjsip" | "sccp"; dialId: string; penalty: number }[];
}

export function renderQueuesConf(rev: number, queues: QueueDef[]): RenderedFile {
  let body = BANNER("queues.conf", rev);
  for (const q of queues) {
    const values: Record<string, string | number> = {
      strategy: q.strategy,
      timeout: q.timeout,
      musicclass: q.musicclass,
      ...q.attrs,
    };
    body += "\n" + ini(q.name, values);
    for (const m of q.members) {
      body += `member => ${dialString(m.tech, m.dialId)},${m.penalty}\n`;
    }
  }
  return { path: "queues.conf", content: body + localInclude("queues.conf") };
}
