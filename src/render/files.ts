/**
 * Config file renderers.
 *
 * Everything here is config that ARI dynamic configuration cannot reach:
 *
 *   - the outbound websocket itself (chicken-and-egg — it cannot arrive over
 *     the connection it configures)
 *   - the sorcery.conf mappings that make ARI writes possible at all; without
 *     them every PUT returns 403 from the read-only flat-file wizard
 *   - PJSIP transports, identifies and registrations, which are retrieved in
 *     bulk at load/reload rather than on demand
 *   - the entire SCCP [general] section, softkey profiles and (!) templates
 *   - the dialplan
 *
 * Every generated file ends with a `#tryinclude <name>_local.conf` escape hatch
 * so an operator can add site-specific config without editing generated
 * output — the thing v1 got wrong by requiring hand-written templates to live
 * outside the repo entirely. See `localInclude` for why it must not be a plain
 * `#include`.
 */

import type { PbxSettings } from "./settings.js";

export interface RenderedFile {
  path: string;
  content: string;
}

const BANNER = (name: string, rev: number) =>
  `;; ${name}
;; Generated by asterisk-extention-manager2 — file revision ${rev}.
;; DO NOT EDIT. Local additions belong in ${name.replace(/\.conf$/, "")}_local.conf.
`;

function ini(section: string, values: Record<string, string | number | boolean>): string {
  const lines = [`[${section}]`];
  for (const [k, v] of Object.entries(values)) {
    if (v === "" || v === undefined || v === null) continue;
    lines.push(`${k} = ${typeof v === "boolean" ? (v ? "yes" : "no") : v}`);
  }
  return lines.join("\n") + "\n";
}

/**
 * `#tryinclude`, never `#include`.
 *
 * A missing `#include` target does not merely warn — it invalidates the entire
 * enclosing file. For a sorcery-backed config that is fatal:
 *
 *   config.c: The file 'websocket_client_local.conf' was listed as a #include
 *             but it does not exist.
 *   res_sorcery_config.c: Contents of config file 'websocket_client.conf' are
 *             invalid and cannot be parsed
 *   ari/config.c: aem: Outbound websocket invalid websocket client id 'aem_ws'
 *
 * Since these files are the escape hatch rather than a requirement, none of
 * them exists on a freshly commissioned box, so `#include` bricked every site
 * on first connect — the websocket client never registered and Asterisk dialled
 * nothing, with no symptom anywhere except the log above.
 */
function localInclude(name: string): string {
  const base = name.replace(/\.conf$/, "");
  return `\n#tryinclude "${base}_local.conf"\n`;
}

