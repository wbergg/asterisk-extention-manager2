export interface StaticObject {
  object_type: string;
  object_id: string;
  attrs: Record<string, string>;
  sort_order: number;
}

export function renderPjsipConf(
  rev: number,
  objects: StaticObject[],
  globals: Record<string, string>,
): RenderedFile {
  let body = BANNER("pjsip.conf", rev);
  body +=
    "\n;; Trunks, transports and identifies only. Extensions are managed over\n" +
    ";; ARI and live in the astdb sorcery backend, not in this file.\n";

  if (Object.keys(globals).length > 0) {
    body += "\n" + ini("global", { type: "global", ...globals });
  }

  // transport -> auth -> aor -> endpoint -> identify -> registration, matching
  // the dependency order res_pjsip resolves references in.
  const order = [
    "transport",
    "auth",
    "aor",
    "endpoint",
    "identify",
    "registration",
    "acl",
  ];
  const sorted = [...objects].sort((a, b) => {
    const d = order.indexOf(a.object_type) - order.indexOf(b.object_type);
    return d !== 0 ? d : a.sort_order - b.sort_order;
  });

  for (const obj of sorted) {
    body += "\n" + ini(obj.object_id, { type: obj.object_type, ...obj.attrs });
  }

  return { path: "pjsip.conf", content: body + localInclude("pjsip.conf") };
}

export interface SccpStaticSection {
  section_type: "softkey_profile" | "template";
  name: string;
  attrs: Record<string, string>;
}

export function renderSccpConf(
  rev: number,
  general: Record<string, string>,
  sections: SccpStaticSection[],
): RenderedFile {
  let body = BANNER("sccp.conf", rev);

  // configuration_source = sorcery is what makes chan_sccp2 register its
  // sorcery types at all; in "file" mode no sorcery instance is opened and
  // nothing is manageable over ARI. Changing it later needs a module restart,
  // not a reload.
  body += "\n" + ini("general", {
    configuration_source: "sorcery",
    ...general,
  });

  const profiles = sections.filter((s) => s.section_type === "softkey_profile");
  if (profiles.length === 0) {
    // A device's softkey_profile defaults to "default", and a device
    // referencing a profile that does not exist is a hard reload failure —
    // which, given SCCP writes ack 200 regardless, would be invisible.
    body +=
      "\n;; Minimum viable profile: every device references one, and a missing\n" +
      ";; profile fails the reload.\n" +
      ini("default", { type: "softkey_profile" });
  }

  for (const s of sections) {
    // (!) marks a template section in Asterisk config syntax.
    const header = s.section_type === "template" ? `${s.name}(!)` : s.name;
    body +=
      "\n" +
      ini(header, {
        ...(s.section_type === "softkey_profile"
          ? { type: "softkey_profile" }
          : {}),
        ...s.attrs,
      });
  }

  return { path: "sccp.conf", content: body + localInclude("sccp.conf") };
}

